import csv
import math

datos_limpios = []
lineas_descartadas = 0

with open("flight_log.csv", "r") as archivo:

    lector = csv.reader(archivo)

    encabezado = next(lector)

    for fila in lector:

        try:
            # Comprobar que tenga 4 columnas
            if len(fila) != 4:
                raise ValueError("Columnas incorrectas")

            # Convertir los datos a numeros
            tiempo = float(fila[0])
            altitud = float(fila[1])
            aceleracion = float(fila[2])
            temperatura = float(fila[3])

            # Comprobar que sean valores validos
            valores = [tiempo, altitud, aceleracion, temperatura]

            if not all(math.isfinite(x) for x in valores):
                raise ValueError("Dato no valido")

            # Guardar el registro limpio
            datos_limpios.append([
                tiempo / 1000,
                altitud,
                aceleracion,
                temperatura
            ])

        except (ValueError, TypeError):
            lineas_descartadas += 1

print("PROCESAMIENTO INICIAL")
print("Registros validos:", len(datos_limpios))
print("Lineas descartadas:", lineas_descartadas)

print("\nPrimeros 5 registros:")
for fila in datos_limpios[:5]:
    print(fila)

#paso 12 filtro de promedio movil
N = 5 # cantidad de muestras para calcular el promedio
altitudes_filtradas = []

for i in range(len(datos_limpios)):
    numero = max(0, i - N + 1)
    ventana = datos_limpios[numero: i + 1]
    promedio = sum(fila[1] for fila in ventana) / len(ventana)
    altitudes_filtradas.append(promedio)

print("FILTRO APLICADO")
