# GENERADOR DE VUELO COMPLETO

import csv
import random
import math

# CONFIGURACION
dt = 0.1
gravedad = 9.81
altitud = 0.0
velocidad = 0.0
tiempo = 0.0

# Listas para guardar la telemetria
datos = []

def registrar_dato(t, h, a):
    # Ruido gaussiano del barometro
    ruido = random.gauss(0, 0.5)
    altitud_medida = max(0, h + ruido)

    # Gradiente termico: 6.5 grados por km
    temperatura = 20 - (6.5 * h / 1000)

    datos.append([
        round(t * 1000),
        round(altitud_medida, 3),
        round(a, 3),
        round(temperatura, 3)
    ])

# FASE 1: EN RAMPA (2 segundos)
for i in range(20):
    tiempo = i * dt
    registrar_dato(tiempo, 0, 9.81)

# FASE 2: PROPULSION (1.5 segundos)
altitud = 0
velocidad = 0

for i in range(1, 16):
    altitud = altitud + velocidad * dt + 0.5 * 60 * dt**2
    velocidad = velocidad + 60 * dt
    tiempo = 2 + i * dt

    registrar_dato(tiempo, altitud, 69.81)

# FASE 3: VUELO BALISTICO
while velocidad > 0:
    altitud = altitud + velocidad * dt - 0.5 * gravedad * dt**2
    velocidad = velocidad - gravedad * dt
    tiempo = tiempo + dt

    registrar_dato(tiempo, altitud, 0)

# FASE 4: PARACAIDAS
while altitud > 0:
    altitud = altitud - 6 * dt
    tiempo = tiempo + dt

    if altitud < 0:
        altitud = 0

    registrar_dato(tiempo, altitud, 9.81)

# FASE 5: EN TIERRA (3 segundos)
for i in range(1, 31):
    tiempo = tiempo + dt
    registrar_dato(tiempo, 0, 9.81)

# CREAR ARCHIVO CSV
with open("flight_log.csv", "w", newline="") as archivo:
    escritor = csv.writer(archivo)

    escritor.writerow([
        "time_ms",
        "altitude_m",
        "accel_z_ms2",
        "temp_c"
    ])

    # Insertar 3 lineas corruptas
    for i, fila in enumerate(datos):
        if i == 30:
            escritor.writerow(["", "ERROR", "69.81", "19.9"])
        if i == 60:
            escritor.writerow(["ERROR", "450", "0", "17"])
        if i == 90:
            escritor.writerow(["5000", "300", "0"])

        escritor.writerow(fila)

print("SIMULACION COMPLETADA")
print("Muestras validas:", len(datos))
print("Archivo creado: flight_log.csv")
print("Altitud maxima:", round(max(f[1] for f in datos), 2), "m")
print("Duracion:", round(datos[-1][0] / 1000, 2), "segundos")

